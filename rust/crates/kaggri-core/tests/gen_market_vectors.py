import math
from kaggle_environments.envs.kaggriculture import kaggriculture as K

P = K.PRODUCTS

def raw_price(item, inventory, params=None):
    p = (params or K.MARKET_PARAMS)[item]
    base = p["base"]; I0 = p["I0"]; T = p["T"]
    if inventory < I0:
        f = p["below_func"]
        amp = p["below_target"] * base / K._shape(f, T, T)
        price = base + amp * K._shape(f, I0 - inventory, T)
    else:
        f = p["above_func"]
        amp = p["above_target"] * base / K._shape(f, T, T)
        price = base - amp * K._shape(f, inventory - I0, T)
    return price

# 1. find all exact .5 raw prices in 9000..11000
halves = []
for i, item in enumerate(P):
    for inv in range(9000, 11001):
        rp = raw_price(item, inv)
        if rp == math.floor(rp) + 0.5:
            halves.append((item, inv, rp, K.market_price(item, inv)))
print("exact .5 cases in 9000..11000:", len(halves))
for h in halves:
    print("   ", h)

# wider sweep for halves
halves_wide = []
for i, item in enumerate(P):
    for inv in range(-2000, 40001):
        rp = raw_price(item, inv)
        if rp == math.floor(rp) + 0.5:
            halves_wide.append((item, inv, rp, K.market_price(item, inv)))
print("exact .5 cases in -2000..40000:", len(halves_wide))
for h in halves_wide[:60]:
    print("   W", h)

invs = set()
invs.update(range(9000, 11001))           # dense around I0
invs.update(range(-3000, 9000, 13))       # coarse below
invs.update(range(11001, 40001, 17))      # coarse above
invs.update([-100000, -50000, -20000, -1, 0, 1, 9999, 10000, 10001, 50000, 100000, 1000000])
invs.update([h[1] for h in halves_wide])
invs = sorted(invs)

with open("rust/crates/kaggri-core/tests/data/market_price_vectors.csv", "w") as f:
    f.write("# generated by tools/gen_market_vectors.py from kaggle_environments 1.32.7\n")
    f.write("# product_index,inventory,expected_price   (product_index indexes PRODUCTS)\n")
    for i, item in enumerate(P):
        for inv in invs:
            f.write(f"{i},{inv},{K.market_price(item, inv)}\n")
print("rows:", 9*len(invs))

# also dump raw (unrounded) prices for a handful, to test _shape/order-of-ops in f64
with open("rust/crates/kaggri-core/tests/data/market_raw_vectors.csv", "w") as f:
    f.write("# product_index,inventory,raw_price_hex(f64 bits as u64 hex)\n")
    import struct
    for i, item in enumerate(P):
        for inv in list(range(9000,11001,7)) + list(range(-3000, 9000, 137)) + list(range(11001, 40001, 211)):
            rp = raw_price(item, inv)
            bits = struct.unpack('<Q', struct.pack('<d', rp))[0]
            f.write(f"{i},{inv},{bits:016x}\n")
print("raw rows written")
